#!/usr/bin/env python3
"""Check that the numbers in the documents match the generated report/CFG.

Run: python3 tools/tests/test_docs_consistency.py [--report PATH]

Only quantities that are generated by the tools are checked here (counts and
the two CFG metrics).  Free-text wording is not machine-checked; the point is
to catch a document that silently keeps an old number after the tools moved.

Results are PASS / FAIL / SKIP.  When the report or the firmware is missing
the corresponding check is a SKIP, never a pass.
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(ROOT / "src" / "mock"))

import cr16_cfg as C  # noqa: E402

REPORT = ROOT / "tools" / "reports" / "cr16-branch-validation.json"
DOCS = {
    "cfg": ROOT / "docs" / "fon-dialog-cr16-cfg.md",
    "branches": ROOT / "docs" / "fon-dialog-cr16-branches.md",
    "periph": ROOT / "docs" / "fon-dialog-peripheral-init.md",
    "facts": ROOT / "docs" / "fon-known-facts.md",
}

fails = 0
skips = 0


def check(name, got, want):
    global fails
    if got == want:
        print(f"PASS {name}")
    else:
        print(f"FAIL {name}: got {got!r} want {want!r}")
        fails += 1


def skip(name, why):
    global skips
    print(f"SKIP {name}: {why}")


def text(key):
    p = DOCS[key]
    return p.read_text() if p.is_file() else ""


if not REPORT.is_file():
    skip("report numbers", f"{REPORT} missing")
    report = None
else:
    report = json.loads(REPORT.read_text())

if report is not None:
    normal = report["summary"]["normal"]["by_status"]
    p2 = report["summary"]["p2test"]["by_status"]
    check("report: normal has zero MISMATCH", normal["MISMATCH"], 0)
    check("report: p2test has zero MISMATCH", p2["MISMATCH"], 0)
    check("report: unsupported entries equal the summary",
          len(report["unsupported"]),
          normal["UNSUPPORTED"] + p2["UNSUPPORTED"])
    check("report: mismatch entries equal the summary",
          len(report["mismatches"]), normal["MISMATCH"] + p2["MISMATCH"])

    # The branch document quotes the per-form match counts.
    br = text("branches").replace("\u2009", "").replace("\u00a0", " ")
    for image, table in report["summary"].items():
        for form, counts in table["by_form"].items():
            if counts["MATCH"] and form in ("bal32", "dispe9", "disps5"):
                # documents may group digits with a thin space, a normal
                # space or nothing at all; normalise before comparing.
                digits = str(counts["MATCH"])
                grouped = f"{counts['MATCH']:,}".replace(",", " ")
                norm = re.sub(r"\s", "", br)
                check(f"docs quote {image} {form} MATCH {digits}",
                      digits in norm, True)

    # The peripheral document states the unsupported total.
    per = text("periph")
    total_unsupported = normal["UNSUPPORTED"] + p2["UNSUPPORTED"]
    norm_all = re.sub(r"\s", "", "".join(text(k) for k in DOCS))
    check(f"a document mentions the unsupported total {total_unsupported}",
          str(total_unsupported) in norm_all, True)

fw_path = ROOT / "firmware" / "dectfw_secondlevel_441.hex"
objdump = Path("/tmp/opencode/cr16/build/binutils/objdump")
if not fw_path.is_file() or not objdump.is_file():
    skip("cfg numbers", "firmware or CR16 objdump missing")
else:
    fw = C.load(str(fw_path))
    C.disassemble(fw, str(objdump))
    edges = C.build(fw)
    st = C.category_stats(edges)
    mode_a = C.reach_all(fw, edges, [0x1602])
    cfg = text("cfg").replace("\u2009", " ").replace("\u00a0", " ")
    norm_cfg = re.sub(r"\s", "", cfg)
    for metric, value in (
            ("DIRECT_RESOLVED", st[C.DIRECT_RESOLVED]),
            ("DIRECT_UNSUPPORTED", st[C.DIRECT_UNSUPPORTED]),
            ("INDIRECT_REGISTER", st[C.INDIRECT_REGISTER])):
        check(f"cfg doc quotes {metric} = {value}",
              f"{metric}`|{value}" in norm_cfg, True)
    check(f"cfg doc quotes mode A = {len(mode_a)}",
          str(len(mode_a)) in norm_cfg, True)
    norm_facts = re.sub(r"\s", "", text("facts"))
    check("a document quotes the decoded instruction count",
          str(len(fw.insns)) in norm_cfg or str(len(fw.insns)) in norm_facts,
          True)

print()
print(f"{fails} failure(s), {skips} skip(s)")
sys.exit(1 if fails else 0)
